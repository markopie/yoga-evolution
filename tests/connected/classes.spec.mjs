import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { createProfile } from '../browser/profile-helpers.mjs';

test('hosted Supabase: Classes, PDF, personal practice, Browse and local backup', async ({ page }) => {
    const payloads = [];
    page.on('request', request => {
        if (request.url().includes('.supabase.co/') && request.postData()) payloads.push(request.postData());
    });
    await createProfile(page, `Classes integration ${new Date().toISOString().slice(0, 16)}`);
    const connection = await page.evaluate(() => ({ target: window.supabaseConfig.target, url: window.supabaseConfig.url, live: window.hasLiveProfileSession }));
    expect(connection.target).not.toBe('browser-test');
    expect(connection.url).toMatch(/^https:\/\/.*\.supabase\.co/);
    expect(connection.live).toBe(true);
    await page.waitForFunction(() => window.courses?.length > 10);
    const sequence = await page.evaluate(() => {
        const suitable = window.courses.filter(c => c.poses?.length > 2 && !c.is_alias && !c.poses.some(p => String(p[0]).startsWith('MACRO:')));
        const course = suitable.find(c => String(c.supabaseId || c.id) === '303') || suitable[0];
        return { id: String(course.supabaseId || course.id), title: course.title };
    });
    await page.locator('#navClasses').click();
    await page.getByRole('button', { name: 'New class', exact: true }).click();
    await page.getByLabel('Class name').fill('Integration class');
    await page.locator('#classesScreen').getByLabel('Choose a sequence').selectOption(sequence.id);
    const recordedProps = page.locator('#classesScreen .class-props input[type="checkbox"]');
    await expect.poll(() => recordedProps.count()).toBeGreaterThan(0);
    expect(await recordedProps.evaluateAll(inputs => inputs.every(input => input.checked))).toBe(true);
    await recordedProps.first().uncheck();
    await page.getByRole('button', { name: 'Add student', exact: true }).click();
    await page.getByLabel('Student name').fill('Example student local only');
    await page.getByLabel('Form received and reviewed').check();
    await page.getByLabel('Reviewed on').fill('2026-10-01');
    await page.getByRole('button', { name: 'Add prop', exact: true }).click();
    await page.getByLabel('Prop', { exact: true }).fill('Example additional prop');
    await expect(page.getByLabel('Include Example additional prop', { exact: true })).toBeChecked();
    await page.getByLabel('Include Example additional prop', { exact: true }).uncheck();
    await page.getByRole('button', { name: 'Save class', exact: true }).click();
    await expect(page.locator('#classesScreen [role="status"]')).toHaveText('Class saved.');
    await page.reload(); await page.locator('#navClasses').click();
    await page.getByRole('button', { name: /Integration class/ }).click();
    await expect(page.locator('.class-sheet-students')).toContainText('Example student local only');
    await expect(page.getByRole('button', { name: 'View sequence', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'Edit class', exact: true }).click();
    await expect(recordedProps.first()).not.toBeChecked();
    await expect(page.getByLabel('Include Example additional prop', { exact: true })).not.toBeChecked();
    expect(await page.locator('#classesScreen select').first().locator('option').count()).toBeGreaterThan(1);
    await page.getByRole('button', { name: 'Cancel changes', exact: true }).click();
    await page.getByRole('button', { name: 'View sequence', exact: true }).click();
    await expect(page.locator('#displayTitle')).toHaveText(sequence.title);
    const pdfDownload = page.waitForEvent('download');
    await page.locator('#editCourseBackdrop').getByRole('button', { name: 'Download PDF', exact: true }).click();
    const pdf = await pdfDownload;
    await pdf.saveAs('.runtime/connected-sequence.pdf');
    const bytes = await readFile(await pdf.path());
    expect(bytes.subarray(0, 5).toString()).toBe('%PDF-');
    expect(bytes.toString()).not.toContain('Example student local only');
    await page.locator('#editCourseCancelBtn').click();
    const coveredDownload = page.waitForEvent('download');
    await page.locator('#classDownloadPdf').click();
    await (await coveredDownload).saveAs('.runtime/connected-class-cover.pdf');
    await page.getByLabel('Include class cover with student names and props').uncheck();
    const plainDownload = page.waitForEvent('download');
    await page.locator('#classDownloadPdf').click();
    await (await plainDownload).saveAs('.runtime/connected-class-plain.pdf');

    await page.getByRole('button', { name: 'Practise sequence', exact: true }).click();
    await page.getByRole('button', { name: 'Start practice', exact: true }).click();
    await page.locator('#focusPauseBtn').click();
    await expect(page.locator('#startStopBtn')).toHaveText('Resume');
    await page.locator('#nextBtn').click(); await page.locator('#prevBtn').click();
    const practice = () => page.evaluate(() => ({ id: window.currentSequence.id, index: window.currentIndex, remaining: window.playbackEngine.remaining }));
    const before = await practice();
    await page.locator('#navClasses').click(); await page.locator('#navProgress').click();
    await expect(page.locator('#historyBackdrop')).toBeVisible();
    await page.locator('#navPractice').click(); expect(await practice()).toEqual(before);
    await page.locator('#manualLibraryPanel > summary').click();
    await page.locator('#browseBtn').click();
    const category = await page.locator('#browseCategory option').nth(1).getAttribute('value');
    await page.locator('#browseCategory').selectOption(category);
    await expect(page.locator('#browseList button').first()).toBeVisible();
    await page.locator('#browseCategory').selectOption('');
    const treeId = await page.evaluate(() => String(Object.values(window.asanaLibrary).find(pose => /tree/i.test(pose.english || '')).id));
    await page.locator('#browseAsanaNo').fill(treeId);
    await page.locator('#browseSearch').fill('Tree');
    await expect(page.locator('#browseList button').first()).toBeVisible();
    await page.locator('#browseList button').first().click();
    await expect(page.locator('#browseDetail .teaching-card')).toBeVisible();
    await expect(page.locator('#browseDetail > .edit-asana-btn')).toHaveCount(0);
    await expect(page.locator('.browse-library-actions .edit-asana-btn')).toHaveText('Edit in my library');
    const variations = page.locator('#browseDetail .teaching-card__variation-trigger');
    if (await variations.count()) {
        await variations.click();
        await page.locator('#browseDetail [role="menuitemradio"]').last().click();
        await expect(variations).toHaveAttribute('aria-expanded', 'false');
    }
    for (const title of ['Base Technique', 'Description']) {
        const details = page.locator('#browseDetail summary').filter({ hasText: title });
        if (await details.count()) await details.click();
    }
    await page.locator('#browseDetail button[aria-label="Play pose audio"]').click();
    await page.locator('#browseCloseBtn').click();
    await page.locator('#returnToPracticeBtn').click();
    page.once('dialog', dialog => dialog.accept()); await page.locator('#endManualPracticeBtn').click();
    await page.locator('#startTodayPracticeBtn').click();
    await page.getByRole('button', { name: 'Start practice', exact: true }).click();
    await page.locator('#focusPauseBtn').click();
    await page.locator('#nextBtn').click();
    await page.locator('#manualLibraryPanel > summary').click();
    await expect(page.locator('#sequenceSelect')).toBeDisabled();
    await page.locator('#navClasses').click();
    await expect(page.locator('#manualLibraryPanel')).toBeHidden();
    await page.locator('#navPractice').click();
    await page.locator('#returnToPracticeBtn').click();
    await page.locator('#exitCurriculumPracticeBtn').click();
    await page.locator('#navClasses').click();
    await page.getByRole('button', { name: /Integration class/ }).click();
    await page.screenshot({ path: '.runtime/connected-classes-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: '.runtime/connected-classes-mobile.png', fullPage: true });
    await page.locator('#settingsToggleButton').click();
    const backupDownload = page.waitForEvent('download'); await page.locator('#exportProfileBtn').click();
    const backup = JSON.parse(await readFile(await (await backupDownload).path(), 'utf8'));
    expect(backup.classes[0].students[0].name).toBe('Example student local only');
    await page.locator('#signOutBtn').click();
    await expect(page.locator('#loginScreen')).toHaveAttribute('data-ready', 'true');
    await page.locator('#profileImportFile').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await expect(page.locator('#mainAppContainer')).toBeVisible();
    await page.locator('#navClasses').click();
    await page.getByRole('button', { name: /Integration class/ }).click();
    await expect(page.locator('.class-sheet-students')).toContainText('Example student local only');
    expect(payloads.some(body => body.includes('p_backup'))).toBe(true);
    expect(payloads.join('\n')).not.toContain('Example student local only');
    expect(payloads.join('\n')).not.toContain('Integration class');
});
